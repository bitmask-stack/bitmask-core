use crate::bp::data::BtcAccountInfo;
use crate::wallet::data::BPWallet;
use bpstd::{Tx, Txid};
use nonasync::persistence::CloneNoPersistence;
use rgbcore::ChainNet;
use serde::{Deserialize, Serialize};

#[derive(Debug)]
pub struct BtcAccount {
    chain_net: ChainNet,
    pub wallet: BPWallet,
}

impl CloneNoPersistence for BtcAccount {
    fn clone_no_persistence(&self) -> Self {
        let BtcAccount { wallet, .. } = self;
        Self {
            chain_net: self.chain_net,
            wallet: wallet.clone_no_persistence(),
        }
    }
}

impl BtcAccount {
    pub fn new(wallet: BPWallet, chain_net: ChainNet) -> Self {
        Self { wallet, chain_net }
    }

    pub fn with(wallet: BPWallet, info: BtcAccountInfo) -> Self {
        Self {
            wallet,
            chain_net: info.chain_net,
        }
    }

    pub fn chain_net(&self) -> ChainNet {
        self.chain_net
    }

    pub fn info(&self) -> BtcAccountInfo {
        let Self { chain_net, .. } = self.clone_no_persistence();

        BtcAccountInfo {
            persistence: None,
            chain_net,
        }
    }
}

#[derive(Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct WalletData {
    pub address: String,
    pub balance: Balance,
    pub transactions: Vec<WalletTransaction>,
    pub utxos: Vec<String>,
}

#[derive(Serialize, Deserialize, Debug, Clone, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct WalletTransaction {
    pub txid: Txid,
    pub received: u64,
    pub sent: u64,
    pub fee: Option<u64>,
    pub confirmed: bool,
    pub confirmation_time: Option<BlockTime>,
    pub vsize: u32,
    pub fee_rate: f32,
}

#[derive(Serialize, Deserialize, Debug, PartialEq, Eq, Clone, Default)]
pub struct Balance {
    /// All coinbase outputs not yet matured
    pub immature: u64,
    /// Unconfirmed UTXOs generated by a wallet tx
    pub trusted_pending: u64,
    /// Unconfirmed UTXOs received from an external wallet
    pub untrusted_pending: u64,
    /// Confirmed and immediately spendable balance
    pub confirmed: u64,
}

#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq, Default)]
pub struct BlockTime {
    /// confirmation block height
    pub height: u32,
    /// confirmation block timestamp
    pub timestamp: u64,
}

#[derive(Serialize, Deserialize, Debug, Clone, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct TransactionData {
    pub details: TransactionDetails,
    pub vsize: usize,
    pub fee_rate: f32,
}

#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq)]
pub struct TransactionDetails {
    /// Optional transaction
    pub transaction: Option<Tx>,
    /// Transaction id
    pub txid: Txid,
    /// Received value (sats)
    /// Sum of owned outputs of this transaction.
    pub received: u64,
    /// Sent value (sats)
    /// Sum of owned inputs of this transaction.
    pub sent: u64,
    /// Fee value (sats) if confirmed.
    /// The availability of the fee depends on the backend. It's never `None` with an Electrum
    /// Server backend, but it could be `None` with a Bitcoin RPC node without txindex that receive
    /// funds while offline.
    pub fee: Option<u64>,
    /// If the transaction is confirmed, contains height and Unix timestamp of the block containing the
    /// transaction, unconfirmed transaction contains `None`.
    pub confirmation_time: Option<BlockTime>,
}
